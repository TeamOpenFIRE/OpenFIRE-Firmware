        switch(i2cDispType) {
            case OF_Const::I2Cdisp_SSD1306:
                display1306->clearDisplay(); break;
            case OF_Const::I2Cdisp_SH1106:
                display1106->clearDisplay(); break;
            case OF_Const::I2Cdisp_SH1107:
                display1107->clearDisplay(); break;
            default: break;
        }
